namespace ScreenCapture.NET;

/// <summary>
/// Represents a display-rotation.
/// </summary>
public enum Rotation
{
    /// <summary>
    /// The display is not rotated.
    /// </summary>
    None = 0,

    /// <summary>
    /// The display is rotated by 90 degrees.
    /// </summary>
    Rotate90 = 90,

    /// <summary>
    /// The display is rotated by 180 degrees.
    /// </summary>
    Rotate180 = 180,

    /// <summary>
    /// The display is rotated by 270 degrees.
    /// </summary>
    Rotate270 = 270
}
